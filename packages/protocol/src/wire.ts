import { z } from "zod";
import { AgentEventSchema, ExtensionUiRequestSchema } from "./events.ts";
import { SessionPresentationSchema } from "./presentation.ts";
import { ImageContentSchema, SessionEntrySchema } from "./messages.ts";
import {
  BashResultSchema,
  SessionStateSchema,
  SessionStatsSchema,
  StreamingBehaviorSchema,
} from "./commands.ts";

/**
 * PiOS wire protocol: the client-to-daemon envelope carried over one
 * WebSocket that multiplexes every session.
 *
 * This is deliberately not pi's RPC protocol. The daemon owns N pi sessions,
 * so every frame needs a `sessionId`, and delivery has to be idempotent across
 * reconnects, so every client-originated frame needs a `commandId`.
 */

/** Bumped on any breaking envelope change. Clients refuse a mismatch. */
export const WIRE_VERSION = 2;

const ClientBase = z.object({
  v: z.literal(WIRE_VERSION),
  /**
   * Idempotency key, generated by the client and stable across retries.
   * The daemon dedupes on it, so a redelivered prompt is not run twice.
   */
  commandId: z.string(),
  sessionId: z.string().optional(),
});

// `.extend` rather than a spread: spreading a generic shape into an object
// literal loses per-member optionality when the type is inferred.
const Envelope = <T extends z.ZodRawShape>(shape: T) => ClientBase.extend(shape);

/**
 * Brings a session into being under an id the client already composed against.
 *
 * A session with no first prompt is an empty composer, not a session, so the
 * draft holds a client-generated id and whichever frame first needs an agent
 * carries this to create it under that exact id.
 */
const SessionCreateSchema = z.object({
  cwd: z.string(),
  name: z.string().optional(),
  /** Explicit: pi's headless trust default is not something to inherit. */
  trustProject: z.boolean().default(false),
  model: z.string().optional(),
});

/** Client-chosen, so a reconnecting device can find its shell again. */
const TerminalIdSchema = z.string().min(1).max(128);
const TerminalCellsSchema = z.number().int().min(1).max(1000);

/**
 * A position in one shell's output. `instance` changes when the shell is
 * replaced, which is what makes an offset from the old one meaningless.
 */
export const TerminalCursorSchema = z.object({
  instance: z.string(),
  offset: z.number().int().min(0),
});
export type TerminalCursor = z.infer<typeof TerminalCursorSchema>;

export const ClientFrameSchema = z.discriminatedUnion("type", [
  // Must succeed before the supervisor reports `connected`.
  Envelope({ type: z.literal("hello"), deviceToken: z.string(), clientVersion: z.string() }),
  /**
   * Every session on disk, whether or not the daemon has a process for it.
   *
   * The session store is the list: one started in the TUI and one started here
   * are the same kind of thing. Paged, because a real history is thousands of
   * conversations and a phone asks for a screenful at a time.
   */
  Envelope({
    type: z.literal("list_sessions"),
    /** Restrict to one project directory. Omitted means every project. */
    cwd: z.string().optional(),
    /** Matched against path, name and preview. Never against transcripts. */
    query: z.string().optional(),
    limit: z.number().optional(),
    offset: z.number().optional(),
  }),
  // Relaunches the same session under new trust; it never forks a new one.
  Envelope({
    type: z.literal("set_session_trust"),
    sessionId: z.string(),
    trustProject: z.boolean(),
  }),
  Envelope({
    type: z.literal("subscribe"),
    sessionId: z.string(),
    /** Last buffered event seq the client holds, for a gapless tail. */
    sinceSeq: z.number().optional(),
  }),
  Envelope({ type: z.literal("unsubscribe"), sessionId: z.string() }),
  /**
   * Models this session can switch to. Scoped only by default: the whole
   * catalogue is hundreds of rows, and asking for it is a deliberate act.
   */
  Envelope({
    type: z.literal("list_models"),
    sessionId: z.string(),
    all: z.boolean().default(false),
    /**
     * Starts the session when it does not exist yet, as `prompt` does.
     *
     * A draft has to offer a model before its first prompt, and the catalogue
     * only exists behind an agent. The id is the one the draft was composed
     * against, so the prompt that follows lands on this same session.
     */
    create: SessionCreateSchema.optional(),
  }),
  /** Slash commands this session can invoke, for composer completion. */
  Envelope({ type: z.literal("list_commands"), sessionId: z.string() }),
  /** Token, cost and context accounting for one session. */
  Envelope({ type: z.literal("get_stats"), sessionId: z.string() }),
  Envelope({
    type: z.literal("set_model"),
    sessionId: z.string(),
    provider: z.string(),
    modelId: z.string(),
  }),
  Envelope({
    type: z.literal("set_thinking_level"),
    sessionId: z.string(),
    level: z.string(),
  }),
  /** pi's `/name`. Persisted in the session file, so the TUI shows it too. */
  Envelope({
    type: z.literal("set_session_name"),
    sessionId: z.string(),
    name: z.string().trim().min(1),
  }),
  /**
   * pi's `/compact`. Acked once pi has started; the run itself is reported
   * by `compaction_start` and `compaction_end` like an automatic one.
   */
  Envelope({
    type: z.literal("compact"),
    sessionId: z.string(),
    customInstructions: z.string().optional(),
  }),
  /** pi's own setting: it applies to every session, here and in the TUI. */
  Envelope({
    type: z.literal("set_auto_compaction"),
    sessionId: z.string(),
    enabled: z.boolean(),
  }),
  /**
   * pi's `/reload`: extensions, skills, templates and context files are read
   * again. RPC mode has no such command, so the agent is relaunched in place
   * and announced with `session_recovered`, as a trust change is.
   */
  Envelope({ type: z.literal("reload_session"), sessionId: z.string() }),
  /**
   * pi's `/export` to HTML. Answered with `exported`. Without a path pi picks
   * one in the session cwd.
   */
  Envelope({
    type: z.literal("export_session"),
    sessionId: z.string(),
    outputPath: z.string().trim().min(1).optional(),
  }),
  /**
   * Transcript, read from the session file.
   *
   * `since` answers "what changed" and `before` answers "what came earlier":
   * two different questions, so two parameters rather than one cursor doing
   * both jobs. Neither given means the tail, or everything without a `limit`.
   */
  Envelope({
    type: z.literal("get_entries"),
    sessionId: z.string(),
    since: z.string().optional(),
    /** Newest N entries. A chat is read from the bottom. */
    limit: z.number().optional(),
    /** Page backwards from this index, as returned in `offset`. */
    before: z.number().optional(),
  }),
  Envelope({
    type: z.literal("prompt"),
    sessionId: z.string(),
    /** Starts the session when it does not exist yet. */
    create: SessionCreateSchema.optional(),
    /** Stable per composed message, survives app restart in the outbox. */
    messageId: z.string(),
    text: z.string(),
    images: z.array(ImageContentSchema).default([]),
    /** Mandatory while the agent streams; the daemon applies it only then. */
    streamingBehavior: StreamingBehaviorSchema.optional(),
  }),
  Envelope({ type: z.literal("interrupt"), sessionId: z.string() }),
  /**
   * One shell command in the session cwd, as pi's `!` does. Not a terminal:
   * there is no PTY, so anything interactive hangs until `abort_bash`.
   *
   * Never queued. A shell command replayed minutes later, against a tree that
   * has moved on, is not what the user asked for.
   */
  Envelope({
    type: z.literal("run_bash"),
    sessionId: z.string(),
    command: z.string(),
    /** pi's `!!`: the output is shown but never reaches the model. */
    excludeFromContext: z.boolean().default(false),
  }),
  /** Cancels the running command. Carries no id: pi allows only one. */
  Envelope({ type: z.literal("abort_bash"), sessionId: z.string() }),
  /**
   * Continues the conversation from just before a user turn, in a new session.
   *
   * The history in front of the turn is copied into a session of its own and
   * the turn's text comes back to be re-composed. This session is unchanged:
   * branching never rewrites a transcript someone might still want.
   */
  Envelope({
    type: z.literal("rewind"),
    sessionId: z.string(),
    /** The user entry to branch before. Its text comes back in `rewound`. */
    entryId: z.string(),
  }),
  Envelope({
    type: z.literal("extension_ui_response"),
    sessionId: z.string(),
    requestId: z.string(),
    value: z.string().optional(),
    confirmed: z.boolean().optional(),
    cancelled: z.boolean().optional(),
  }),
  /**
   * Attaches to a shell on a daemon-owned PTY, starting one if the id has
   * none. Unrelated to `run_bash`: this is an interactive terminal, and
   * nothing it prints reaches the agent.
   *
   * The shell outlives the socket, so a reconnect sends this again with
   * `since` and receives only what it missed.
   */
  Envelope({
    type: z.literal("terminal_open"),
    terminalId: TerminalIdSchema,
    cwd: z.string(),
    cols: TerminalCellsSchema,
    rows: TerminalCellsSchema,
    /** Where the client's copy of the output ends. Absent replays everything. */
    since: TerminalCursorSchema.optional(),
    /**
     * Replaces an exited shell with a fresh one. Never implied: a reconnect
     * that silently restarted a finished shell would lose its exit status.
     */
    restart: z.boolean().default(false),
  }),
  /** Keystrokes and pastes. Not acked: a reply per key doubles the traffic. */
  Envelope({
    type: z.literal("terminal_input"),
    terminalId: TerminalIdSchema,
    data: z.string().max(256 * 1024),
  }),
  /** The last device to resize wins, as with a shared tmux window. */
  Envelope({
    type: z.literal("terminal_resize"),
    terminalId: TerminalIdSchema,
    cols: TerminalCellsSchema,
    rows: TerminalCellsSchema,
  }),
  /** Stops streaming to this socket. The shell keeps running. */
  Envelope({ type: z.literal("terminal_detach"), terminalId: TerminalIdSchema }),
  /** Hangs up the shell, for every device attached to it. */
  Envelope({ type: z.literal("terminal_close"), terminalId: TerminalIdSchema }),
  /** Activity lease: what the client wants kept warm, not a liveness ping. */
  Envelope({
    type: z.literal("activity"),
    visible: z.boolean(),
    focused: z.boolean(),
    appState: z.enum(["active", "inactive", "background"]),
    sessionIds: z.array(z.string()).default([]),
  }),
]);
export type ClientFrame = z.infer<typeof ClientFrameSchema>;

export const ModelOptionSchema = z.object({
  provider: z.string(),
  modelId: z.string(),
  name: z.string(),
  /**
   * In the model scope pi was configured with (`--models`). The picker shows
   * these alone until the user asks for everything, because an unfiltered
   * catalogue is hundreds of rows on a phone.
   */
  scoped: z.boolean().default(false),
});
export type ModelOption = z.infer<typeof ModelOptionSchema>;

/**
 * A slash command, invoked by sending `/name args` as an ordinary prompt.
 * Loose: pi has grown the provenance fields more than once, and an unknown
 * field must not cost the client the whole list.
 */
export const CommandOptionSchema = z.looseObject({
  /** Without the leading slash. May carry a collision suffix like `review:1`. */
  name: z.string(),
  description: z.string().optional(),
  source: z.enum(["extension", "prompt", "skill"]).optional(),
  /** Provenance, normalised by the host across pi's shapes for it. */
  scope: z.string().optional(),
  path: z.string().optional(),
});
export type CommandOption = z.infer<typeof CommandOptionSchema>;

export const SessionSummarySchema = z.object({
  sessionId: z.string(),
  name: z.string().optional(),
  cwd: z.string(),
  /**
   * `cold` is the resting state: no process, transcript on disk, wakes on the
   * next command. `crashed` is reported, never hidden behind a silent restart.
   */
  status: z.enum(["cold", "idle", "running", "crashed"]),
  /**
   * Blocked on an extension dialog. Kept beside `status` rather than folded
   * into it: the agent is still running, it just cannot proceed without an
   * answer, and only a client attached to the session can give one.
   */
  awaitingInput: z.boolean().default(false),
  trusted: z.boolean().default(false),
  /**
   * Durable cursor: survives restarts, covers only what pi persisted. Null for
   * a cold session, whose cursor is whatever `get_entries` reads off disk.
   */
  leafId: z.string().nullable().default(null),
  /**
   * Live cursor: the newest buffered event. A client subscribes with this to
   * tail without replaying history it does not want.
   */
  lastSeq: z.number().default(0),
  updatedAt: z.number(),
  /**
   * Last prompt or shell command, which is what the list is ordered by: an
   * agent working unattended keeps `updatedAt` moving, this stays put.
   * Absent from an older daemon; `updatedAt` stands in.
   */
  activeAt: z.number().optional(),
  /** Entries in the transcript, absent when counting one would cost a read. */
  messageCount: z.number().optional(),
  /** First user message, for a row that reads without opening the session. */
  preview: z.string().optional(),
  /** The model the agent is on right now, absent when pi has not resolved one. */
  model: ModelOptionSchema.optional(),
  /** Effective thinking level, absent until pi resolves one. */
  thinkingLevel: z.string().optional(),
  /**
   * Levels the current model accepts. Model-dependent, so it travels with the
   * summary that carries the model rather than being assumed by the client.
   */
  thinkingLevels: z.array(z.string()).default([]),
  /** Whether pi compacts on its own near the context limit; absent until known. */
  autoCompaction: z.boolean().optional(),
});
export type SessionSummary = z.infer<typeof SessionSummarySchema>;


const ServerBase = z.object({
  v: z.literal(WIRE_VERSION),
  /** Echoed from the request that caused this frame, when there was one. */
  commandId: z.string().optional(),
  sessionId: z.string().optional(),
});

const ServerEnvelope = <T extends z.ZodRawShape>(shape: T) => ServerBase.extend(shape);

export const ServerFrameSchema = z.discriminatedUnion("type", [
  ServerEnvelope({
    type: z.literal("welcome"),
    serverVersion: z.string(),
    piVersion: z.string(),
    sessions: z.array(SessionSummarySchema),
  }),

  ServerEnvelope({
    type: z.literal("ack"),
    commandId: z.string(),
    /** True when this command was already applied and was not run again. */
    duplicate: z.boolean().default(false),
  }),
  ServerEnvelope({
    type: z.literal("subscribed"),
    sessionId: z.string(),
    /** Seq the replay ended at; the client tails from here. */
    seq: z.number(),
    /**
     * Buffered events were evicted before the client's cursor, so the tail is
     * incomplete and it must resync with `get_entries`.
     */
    gap: z.boolean().default(false),
  }),
  ServerEnvelope({
    type: z.literal("error"),
    code: z.enum([
      "unauthorized",
      "unknown_session",
      "unknown_cursor",
      "bad_request",
      "agent_busy",
      "internal",
    ]),
    message: z.string(),
  }),
  /** One page of the session list. `offset` 0 replaces, anything else appends. */
  ServerEnvelope({
    type: z.literal("sessions"),
    sessions: z.array(SessionSummarySchema),
    offset: z.number().default(0),
    total: z.number().default(0),
    hasMore: z.boolean().default(false),
  }),
  /**
   * The session store changed on disk, e.g. the TUI started or advanced a
   * session. A nudge with no payload: the client re-lists the page it is on
   * rather than the daemon guessing which one that is.
   */
  ServerEnvelope({ type: z.literal("sessions_changed") }),
  ServerEnvelope({
    type: z.literal("models"),
    sessionId: z.string(),
    models: z.array(ModelOptionSchema),
    /**
     * The whole catalogue, not the scope. Set even for a scoped request when
     * the daemon has no scope to narrow to, so the client never shows an empty
     * picker and calls it a scope.
     */
    all: z.boolean().default(false),
  }),
  ServerEnvelope({
    type: z.literal("commands"),
    sessionId: z.string(),
    commands: z.array(CommandOptionSchema),
  }),
  ServerEnvelope({
    type: z.literal("session_stats"),
    sessionId: z.string(),
    stats: SessionStatsSchema,
  }),
  /** Reply to `export_session`: where the file landed, absolute. */
  ServerEnvelope({
    type: z.literal("exported"),
    sessionId: z.string(),
    path: z.string(),
  }),
  ServerEnvelope({
    type: z.literal("session_state"),
    sessionId: z.string(),
    summary: SessionSummarySchema,
    state: SessionStateSchema.optional(),
  }),
  /** Delta reply to `get_entries`. `leafId` detects a moved branch. */
  ServerEnvelope({
    type: z.literal("entries"),
    sessionId: z.string(),
    entries: z.array(SessionEntrySchema),
    leafId: z.string().nullable(),
    /** True when the cursor was rejected and the client must drop its cache. */
    reset: z.boolean().default(false),
    /** Index of the first entry returned, for the next `before`. */
    offset: z.number().default(0),
    /** Entries in the whole transcript, for knowing whether more remain. */
    total: z.number().default(0),
  }),
  /** A pi event, forwarded verbatim, tagged with its session. */
  ServerEnvelope({
    type: z.literal("agent_event"),
    sessionId: z.string(),
    /** Ring-buffer sequence, for detecting a gap in a live subscription. */
    seq: z.number(),
    /**
     * Daemon epoch ms at publish. The client's only handle on the clock offset
     * between the two machines, which it needs to age a running tool call.
     */
    at: z.number().optional(),
    event: AgentEventSchema,
  }),
  ServerEnvelope({
    type: z.literal("extension_ui_request"),
    sessionId: z.string(),
    request: ExtensionUiRequestSchema,
  }),
  /**
   * The dialog is resolved and must be dismissed everywhere: answered by
   * another device, expired on the daemon's deadline, or lost with the agent.
   */
  ServerEnvelope({
    type: z.literal("extension_ui_closed"),
    sessionId: z.string(),
    requestId: z.string(),
  }),
  /**
   * Snapshot of the non-blocking extension UI, sent on subscribe. Live updates
   * arrive as `extension_ui_request`; this is what a client that missed them
   * needs in order to show the same thing.
   */
  ServerEnvelope({
    type: z.literal("extension_ui_state"),
    sessionId: z.string(),
    presentation: SessionPresentationSchema,
  }),
  /**
   * A shell command started or finished, broadcast to every subscriber.
   *
   * Output arrives in between as `bash_execution_update` agent events, which
   * carry no command text, so this is what gives them a heading and an end.
   */
  ServerEnvelope({
    type: z.literal("bash_state"),
    sessionId: z.string(),
    command: z.string(),
    excludeFromContext: z.boolean().default(false),
    running: z.boolean(),
    /** Present once the command has finished. */
    result: BashResultSchema.optional(),
  }),
  /**
   * Reply to `terminal_open`, ahead of any output. `reset` means the client's
   * copy is not continuous with what follows and the screen must be cleared.
   */
  ServerEnvelope({
    type: z.literal("terminal_attached"),
    terminalId: z.string(),
    instance: z.string(),
    /** Output offset the replay starts at. */
    offset: z.number(),
    reset: z.boolean(),
  }),
  /**
   * Shell output, as text. `offset` is where `data` starts in the shell's
   * output, so a client can tell a duplicate from a gap.
   */
  ServerEnvelope({
    type: z.literal("terminal_output"),
    terminalId: z.string(),
    offset: z.number(),
    data: z.string(),
  }),
  /** The shell is gone. Sent once live, and again on every later attach. */
  ServerEnvelope({
    type: z.literal("terminal_exit"),
    terminalId: z.string(),
    exitCode: z.number(),
    signal: z.number().optional(),
  }),
  /** Reply to `rewind`: where the branch now lives, and what to re-compose. */
  ServerEnvelope({
    type: z.literal("rewound"),
    /** The session branched from, which is unchanged. */
    sessionId: z.string(),
    /** The new session holding the history before the turn. Open this one. */
    branchSessionId: z.string(),
    text: z.string().optional(),
  }),
  /**
   * The transcript was replaced under the client and its cache is stale: pi
   * was restarted from its JSONL after a crash, or the branch was rewound.
   */
  ServerEnvelope({
    type: z.literal("session_recovered"),
    sessionId: z.string(),
    leafId: z.string().nullable(),
    reason: z.string(),
  }),
]);
export type ServerFrame = z.infer<typeof ServerFrameSchema>;

export function isWireVersionMismatch(raw: unknown): boolean {
  return (
    typeof raw === "object" &&
    raw !== null &&
    "v" in raw &&
    (raw as { v: unknown }).v !== WIRE_VERSION
  );
}
